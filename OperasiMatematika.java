package TugaspraktikumPBO_P2;

public class OperasiMatematika {
    public static void main (String[] args){
        double x = 22;
        double y = 33;
        
        System.out.println("22 + 33 = " + (x + y));
        System.out.println("22 - 33 = " + (x - y));
        System.out.println("22 * 33 = " + (x * y));
        System.out.println("22 / 33 = " + (x / y));
        
    }
}
